function rectStroke(
  id: string,
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color: string,
  fillColor: string,
  fillTransparency: number,
  width = 2.2,
  zOrder = 1
): StrokeObject {
  return {
    id,
    layerId: "layer-1",
    tool: "pen",
    penType: "ballpoint",
    isShape: true,
    shapeType: "rectangle",
    color,
    width,
    opacity: 1,
    points: [
      { x: x1, y: y1, pressure: 0.8 },
      { x: x2, y: y1, pressure: 0.8 },
      { x: x2, y: y2, pressure: 0.8 },
      { x: x1, y: y2, pressure: 0.8 },
      { x: x1, y: y1, pressure: 0.8 },
    ],
    zOrder,
    fillStyle: "solid",
    fillColor,
    fillTransparency,
  };
}

