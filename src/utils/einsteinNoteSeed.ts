const pt = (x: number, y: number, pressure = 0.65): BezierPoint => ({ x, y, pressure });

function makeLineStroke(
  id: string,
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color = '#991b1b',
  width = 2.2,
  groupId?: string,
  layerId = 'layer-2'
): StrokeObject {
  return {
    id,
    layerId,
    tool: 'pen',
    penType: 'ballpoint',
    color,
    width,
    opacity: 1,
    isShape: true,
    shapeType: 'line',
    groupId,
    points: [pt(x1, y1), pt(x2, y2)],
  };
}

function makeCircleStroke(
  id: string,
  cx: number,
  cy: number,
  r: number,
  color = '#991b1b',
  width = 2.4,
  fillColor?: string,
  groupId?: string,
  layerId = 'layer-2'
): StrokeObject {
  const pts: BezierPoint[] = [];
  const steps = 32;
  for (let i = 0; i <= steps; i++) {
    const a = (i / steps) * Math.PI * 2;
    pts.push(pt(Math.round((cx + Math.cos(a) * r) * 10) / 10, Math.round((cy + Math.sin(a) * r) * 10) / 10));
  }
  return {
    id,
    layerId,
    tool: 'pen',
    penType: 'ballpoint',
    color,
    width,
    opacity: 1,
    isShape: true,
    shapeType: 'circle',
    fillColor,
    groupId,
    points: pts,
  };
}

